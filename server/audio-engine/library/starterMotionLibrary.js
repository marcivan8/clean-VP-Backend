'use strict';

/**
 * server/audio-engine/library/starterMotionLibrary.js
 *
 * R103 — the Motion Design Knowledge Base, seed library.
 *
 * WHAT THIS IS
 * ------------
 * VIBED's motion vocabulary was, until this file, hardcoded art direction:
 * 14 presets across four components in `client/src/motion/SceneComposer.js`'s
 * LOOKS table and five tones in `SceneDirector.js`. Good defaults, but a
 * closed set and not retrievable — nothing could ask "what should a big
 * spoken number look like in a punchy short" and get an answer.
 *
 * Each row here is a TECHNIQUE: a named, searchable, tagged combination of
 * verbs the motion engine can already execute, with the craft reason for it
 * written down. Retrieval lives in `MotionTechniqueIndex.js`; the scene-plan
 * route injects the shortlist into the model's prompt so a beat can be given
 * a technique by id instead of the model free-forming verb names.
 *
 * THREE RULES THIS FILE FOLLOWS
 * -----------------------------
 * 1. **Nothing here names motion the engine would reject.** `enter` is always
 *    an `in`-group verb, `emphasis` an `emphasis`-group verb (or null), `exit`
 *    an `out`-group verb — the exact contract
 *    `SceneComposer.cleanMotionOverride` validates field by field. The verb
 *    lists are deliberately NOT copied into this file:
 *    `MotionComposer.VERBS` stays the single source of truth and
 *    `scripts/test_motion_knowledge_base.mjs` asserts every row against it,
 *    so a typo here fails a test instead of silently falling back to a look's
 *    own motion at render time. (A third copy of the verb list is exactly the
 *    drift class CLAUDE.md keeps counting.)
 *
 *    Note the one asymmetry that costs us: the engine's five `hold` verbs
 *    (float, breathe, sway, drift, push-in) cannot ride in a beat's motion
 *    object at all, because `cleanMotionOverride` only passes
 *    enter/emphasis/exit/energy and checks the emphasis slot for group
 *    `'emphasis'`. So a technique that wants a living hold has to settle for a
 *    quiet emphasis verb (`nod`, `pulse`) or none, and says so in its `note`.
 *
 * 2. **The taxonomy is the one the asset engine already uses** —
 *    `EditingIntent`, `EmotionTag`, `energyLevel` 1-5, `searchKeywords`,
 *    `bestUseCases`, `compatibleTimelineEvents` — the same fields
 *    `starterLibrary.js` tags SFX with, because `AssetType.ANIMATION` is
 *    already declared in `types.js` and has never had a single row. Keeping
 *    the shapes identical is what makes seeding these into the `assets` table
 *    later (for embedding search through the existing three-pass
 *    AssetSearchEngine) a straight mapping rather than a rewrite.
 *
 * 3. **The content is VIBED's own.** Every technique is a combination of
 *    VIBED's existing verbs and presets, and every `note` is written from
 *    first-principles motion craft. Nothing is lifted from the external
 *    motion repos surveyed in `research-motion-engine-external-repos.md`:
 *    four of the six are built on Remotion, whose licence forbids copying it
 *    into a commercial derivative, and two of those carry no LICENSE file at
 *    all. Principles are not copyrightable; wording is.
 *
 * FIELDS
 * ------
 *   name         slug, unique — the retrieval id, and the `onConflict` key if
 *                this is ever seeded into `assets`
 *   motion       { enter, emphasis|null, exit|null, energy 0-1 } — executable
 *   mood         one of `MotionComposer.MOODS`
 *   component    a `LOOKS` component, when the technique implies one
 *   preset       that component's preset
 *   stagger      seconds between sibling layers inside the beat
 *   beatKinds    `SceneDirector.BEAT_KINDS` this suits
 *   tones        `SceneDirector.TONES` keys this suits
 *   note         the craft reason, one or two sentences. This is the part that
 *                makes the library a knowledge base rather than a preset
 *                list, and it is what the model reads when it picks.
 */

