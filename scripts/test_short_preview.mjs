// scripts/test_short_preview.mjs
//
// R93: the finished short plays in the editor's player and the main edit comes
// back exactly; nothing is saved while previewing; every short gets a 9:16
// picture framed like its export.
import { register } from 'module';
register('./lib/clientLoaderHooks.mjs', import.meta.url);
import assert from 'assert/strict';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

globalThis.localStorage = { _m: {}, getItem(k) { return this._m[k] ?? null; }, setItem(k, v) { this._m[k] = String(v); }, removeItem(k) { delete this._m[k]; } };
globalThis.window = globalThis; globalThis.addEventListener = () => {}; globalThis.removeEventListener = () => {}; globalThis.innerWidth = 1200;
globalThis.fetch = async () => ({ ok: false, status: 503, json: async () => ({}), text: async () => '' });
const log = console.log; console.log = () => {}; console.warn = () => {}; console.info = () => {}; console.error = () => {};

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');
let failures = 0;
async function check(name, fn) {
    try { await fn(); log(`✓ ${name}`); } catch (err) { failures += 1; log(`✗ ${name}\n    ${err.message}`); }
}

const { default: S } = await import('../client/src/store/useTimelineStore.js');
const SF = await import('../client/src/agent/shortFinisher.js');
const TH = await import('../client/src/utils/captureShortThumbnail.js');
const tm = globalThis.timelineManager;
// Entity ids are regenerated by every legacy round trip (the same as a project reload); compare without them.
const shape = (tracks) => JSON.stringify(tracks, (k, v) => (k === 'clipId' ? undefined : v));

const words = [];
for (let i = 0; i < 200; i++) words.push({ word: i % 10 === 9 ? 'done.' : 'word', start: 20 + i * 0.3, end: 20 + i * 0.3 + 0.25 });
const MAIN = [
    { id: 'track-default-video', type: 'video', name: 'V', clips: [{ id: 'v1', clipId: 'ev1', assetId: 'a', type: 'video', start: 0, duration: 120, offset: 5, speed: 1 }] },
    { id: 'tt', type: 'text', name: 'Captions', clips: [{ id: 'cap', clipId: 'ec', type: 'text', content: 'hello', start: 20, duration: 60, words }] },
];
const ASSETS = [{ id: 'a', type: 'video', name: 'talk.mp4', width: 1920, height: 1080, duration: 200, proxyUrl: 'proxy/talk.mp4' }];
const SHORT = { id: 's1', platform: 'tiktok', start: 30, end: 58, title: 'x', events: [{ type: 'REVEAL', timelineTime: 34 }] };

function loadMain() {
    tm.fromLegacyTracks(MAIN);
    S.setState({ tracks: tm.toLegacyTracks(), duration: 120, aspectRatio: '16:9', assets: ASSETS, captions: words, shorts: [SHORT],
        past: [{ tracks: [], marker: 'main-undo' }], future: [], currentTime: 12, activeClipId: 'v1', selectedClipIds: ['v1'], shortPreview: null });
}

log('\nShort preview in the editor player');
await check('Preview loads the finished 9:16 short; Back puts the main edit, undo and playhead back exactly', async () => {
    loadMain();
    const before = shape(S.getState().tracks);
    const built = await SF.finishShort(S.getState(), SHORT, { sfx: false, plan: null });
    assert.equal(S.getState().startShortPreview(SHORT, built, { label: 'TikTok' }), true);
    const p = S.getState();
    assert.equal(p.aspectRatio, '9:16');
    assert.ok(Math.abs(p.duration - built.duration) < 1e-6);
    assert.equal(p.past.length, 0, 'undo cannot reach into the main edit while previewing');
    // R109 — playback starts one task later, on purpose, and this is the shape
    // of the fix rather than an implementation detail: the preview has to land
    // PAUSED at 0 first so VideoPlayer's effect runs `engine.seek(0)`, because
    // `PlaybackEngine.play()` returns immediately when it is already PLAYING
    // and would otherwise carry on decoding from wherever the main edit was.
    assert.equal(p.isPlaying, false, 'the preview must land paused so the engine can seek to 0');
    assert.equal(p.currentTime, 0, 'the playhead must be at the top of the short');
    await new Promise(resolve => setTimeout(resolve, 0));
    assert.equal(S.getState().isPlaying, true, 'the preview never actually started playing');
    assert.ok(p.tracks.some(t => t.clips.some(c => String(c.id).startsWith('short-hook-text-'))), 'the hook title is on the player timeline');
    assert.equal(S.getState().shortPreview.shortId, SHORT.id, 'the preview was dropped by the deferred start');
    assert.ok(p.tracks.find(t => t.type === 'video').clips[0].virtualCam, 'speaker framing travels to the player');
    assert.equal(p.shortPreview.label, 'TikTok');
    assert.equal(S.getState().exitShortPreview(), true);
    const r = S.getState();
    assert.equal(shape(r.tracks), before);
    assert.equal(r.aspectRatio, '16:9');
    assert.equal(r.duration, 120);
    assert.equal(r.currentTime, 12);
    assert.equal(r.past[0].marker, 'main-undo');
    assert.equal(r.captions, words);
    assert.equal(r.shortPreview, null);
});
await check('previewing another short still returns to the MAIN edit, not the previous short', async () => {
    loadMain();
    const before = shape(S.getState().tracks);
    const a = await SF.finishShort(S.getState(), SHORT, { sfx: false, plan: null });
    S.getState().startShortPreview(SHORT, a, {});
    const other = { ...SHORT, id: 's2', start: 60, end: 75 };
    const main = { ...S.getState(), ...S.getState().shortPreview.saved };
    S.getState().startShortPreview(other, await SF.finishShort(main, other, { sfx: false, plan: null }), {});
    assert.equal(S.getState().shortPreview.shortId, 's2');
    S.getState().exitShortPreview();
    assert.equal(shape(S.getState().tracks), before);
});
await check('nothing is saved while previewing; loading a project drops the preview', async () => {
    loadMain();
    const built = await SF.finishShort(S.getState(), SHORT, { sfx: false, plan: null });
    S.getState().startShortPreview(SHORT, built, {});
    localStorage.removeItem('vp_autosave');
    assert.equal(S.getState().saveProject(), null);
    assert.equal(localStorage.getItem('vp_autosave'), null);
    S.getState().loadProject({ tracks: MAIN, duration: 120, aspectRatio: '16:9' });
    assert.equal(S.getState().shortPreview, null);
    assert.equal(S.getState().exitShortPreview(), false, 'no stale main edit to restore into another project');
    assert.ok(S.getState().saveProject(), 'saving works again');
});
await check('wired: player bar, main Export, prompts and Save leave the preview first', () => {
    const ide = read('client/src/layouts/IDELayout.jsx');
    assert.match(ide, /<ShortPreviewBar \/>/);
    assert.match(ide, /if \(!override\) useTimelineStore\.getState\(\)\.exitShortPreview\(\)/);
    assert.match(read('client/src/agent/WorkflowController.js'), /exitShortPreview/);
    const bar = read('client/src/components/Player/ShortPreviewBar.jsx');
    assert.match(bar, /Escape/);
    assert.match(bar, /useEffect\(\(\) => \(\) => \{ useTimelineStore\.getState\(\)\.exitShortPreview\(\); \}, \[\]\)/, 'leaving the editor restores the main edit');
    const panel = read('client/src/components/ShortsPanel.jsx');
    assert.match(panel, /startShortPreview\(short, built/);
    assert.match(panel, /mediaExecutionEngine\._ensureMatte/, 'pop-out bakes through the engine');
    assert.doesNotMatch(panel, /bakeClipMatte/);
    for (const lang of ['en', 'fr']) {
        const sp = JSON.parse(read(`client/src/locales/${lang}/editor.json`)).shortsPanel;
        for (const k of ['previewing', 'previewNote', 'previewBack', 'previewReplay', 'previewStop', 'previewFailed']) assert.ok(sp[k], `${lang}.${k}`);
        assert.doesNotMatch(JSON.stringify(sp), /—/);
    }
});

log('\nShort thumbnails');
await check('the picture is taken at the short\'s first moment, in the export\'s speaker framing', () => {
    loadMain();
    const plan = TH.planShortThumbnail(S.getState(), SHORT);
    assert.equal(plan.assetId, 'a');
    // short time 0 = 29.85 on the timeline; the REVEAL at 34 is 4.15 s in; source = offset 5 + 34
    assert.ok(Math.abs(plan.sourceTime - 39) < 0.01, `source time ${plan.sourceTime}`);
    assert.ok(plan.crop && plan.crop.cropW > 0.3 && plan.crop.cropW < 0.33, '9:16 out of 16:9');
    const r = TH.sourceRect(1920, 1080, plan.crop);
    assert.ok(Math.abs(r.sw / r.sh - 180 / 320) < 1e-6);
    assert.ok(r.sx >= 0 && r.sx + r.sw <= 1920);
});
await check('no moment: a beat after the start; centred crop when the shape is unknown', () => {
    loadMain();
    const plan = TH.planShortThumbnail({ ...S.getState(), assets: [{ id: 'a' }] }, { ...SHORT, events: [] });
    assert.ok(plan.sourceTime > 5 + 29.85 && plan.sourceTime < 5 + 32, `source time ${plan.sourceTime}`);
    assert.equal(plan.crop, null);
    const r = TH.sourceRect(1920, 1080, null);
    assert.equal(r.sx, (1920 - r.sw) / 2);
});
await check('proxy first, then the live file, then the stored source; key changes when the short moves', () => {
    assert.deepEqual(TH.videoUrlsFor({ proxyUrl: 'raw/u/p.mp4', url: 'blob:x', sourceUrl: 'https://storage.googleapis.com/bkt/raw/u/s.mp4' }),
        ['/api/proxy/gcs-media/raw/u/p.mp4', 'blob:x', '/api/proxy/gcs-media/raw/u/s.mp4']);
    assert.notEqual(TH.thumbnailKey(SHORT), TH.thumbnailKey({ ...SHORT, start: 31 }));
    assert.doesNotMatch(read('client/src/utils/captureShortThumbnail.js'), /updateShort/, 'pictures are not saved into the project');
});

log('\nR109 — the preview actually starts, and stops waiting');

await check('entering a preview puts the playhead at 0 before anything plays', async () => {
    loadMain();
    const built = await SF.finishShort(S.getState(), SHORT, { sfx: false, plan: null });
    S.setState({ currentTime: 47, isPlaying: true });
    S.getState().startShortPreview(SHORT, built, {});
    // The engine decodes from its own clock. A preview that leaves the clock
    // at the main edit's position plays the wrong part of the file, or
    // nothing at all when that position is past the short's end.
    assert.equal(S.getState().currentTime, 0, 'the playhead stayed where the main edit was');
    assert.equal(S.getState().isPlaying, false, 'it never paused, so the engine could not seek');
    await new Promise(resolve => setTimeout(resolve, 0));
    assert.equal(S.getState().isPlaying, true);
    S.getState().exitShortPreview();
});

await check('leaving a preview puts the playhead back where the edit was', async () => {
    loadMain();
    const built = await SF.finishShort(S.getState(), SHORT, { sfx: false, plan: null });
    S.getState().startShortPreview(SHORT, built, {});
    await new Promise(resolve => setTimeout(resolve, 0));
    S.setState({ currentTime: 9 });
    S.getState().exitShortPreview();
    assert.equal(S.getState().currentTime, 12, "the main edit came back at the short's position");
    assert.equal(S.getState().isPlaying, false);
});

await check('a preview dropped before it starts does not strand playback', async () => {
    loadMain();
    const built = await SF.finishShort(S.getState(), SHORT, { sfx: false, plan: null });
    S.getState().startShortPreview(SHORT, built, {});
    S.getState().exitShortPreview();          // before the deferred start fires
    await new Promise(resolve => setTimeout(resolve, 0));
    assert.equal(S.getState().shortPreview, null);
    assert.equal(S.getState().isPlaying, false, 'the main edit was left playing a preview that is gone');
});

await check('the thumbnail grab asks for metadata, not the whole file', () => {
    // `preload = 'auto'` asks the browser to buffer the entire source for ONE
    // frame, once per short, in series — competing with the editor's own
    // playback for bandwidth and decoders on exactly the screen where someone
    // is waiting to watch something.
    const src = read('client/src/utils/captureShortThumbnail.js');
    assert.match(src, /video\.preload = 'metadata'/, 'the grab still preloads the whole video');
    assert.ok(!/video\.preload = 'auto'/.test(src), "'auto' is still there");
    const m = src.match(/setTimeout\(\(\) => finish\(null\), (\d+)\)/);
    assert.ok(m, 'the grab has no timeout at all');
    assert.ok(Number(m[1]) <= 5000, `${m[1]}ms per source, per short, in series`);
});

await check('preview scene planning never waits for a generative scene model', async () => {
    const saved = globalThis.fetch;
    const requests = [];
    globalThis.fetch = async (url) => {
        requests.push(String(url));
        return { ok: false, status: 503, json: async () => ({}), text: async () => '' };
    };
    try {
        loadMain();
        const built = await SF.finishShort(S.getState(), SHORT, {
            plan: null, motionTechniques: [], visualContext: [], sfx: false,
        });
        assert.ok(built.applied.some(item => /hook sequence/.test(item)), 'the local scene plan did not reach the short');
        assert.ok(requests.every(url => !url.includes('/api/motion/scene-plan')), 'preview requested the AI scene planner');
    } finally { globalThis.fetch = saved; }
});

await check('Motion KB lookup uses a short deadline and keeps executable techniques', async () => {
    const saved = globalThis.fetch;
    let request;
    globalThis.fetch = async (url, options = {}) => {
        request = { url: String(url), options };
        return { ok: true, status: 200, json: async () => ({ techniques: [{
            name: 'hook-word-reveal-speech', beatKinds: ['intro'], searchKeywords: ['speech'],
            bestUseCases: ['a spoken hook'], tones: ['editorial'],
            motion: { enter: 'word-reveal', exit: 'fade-out', energy: 0.55 },
        }] }) };
    };
    try {
        const techniques = await SF.fetchShortMotionTechniques('this is spoken', 'reels');
        assert.equal(techniques[0].motion.enter, 'word-reveal');
        assert.match(request.url, /\/api\/motion\/techniques$/);
        assert.equal(JSON.parse(request.options.body).limit, 24);
        assert.ok(request.options.signal, 'technique lookup has no abort deadline');
    } finally { globalThis.fetch = saved; }
});

await check('upload visual profiles are read as local planner context', async () => {
    const saved = globalThis.fetch;
    let requestedUrl = '';
    globalThis.fetch = async url => {
        requestedUrl = String(url);
        return { ok: true, status: 200, json: async () => ({ profiles: [{ sceneType: 'coffee preparation' }] }) };
    };
    try {
        const profiles = await SF.fetchShortVisualContext('project-7');
        assert.match(requestedUrl, /broll-profiles\?projectId=project-7/);
        assert.equal(profiles[0].sceneType, 'coffee preparation');
    } finally { globalThis.fetch = saved; }
});

await check('R120 — the client never gives up on a plan before the server\'s own budget does', () => {
    // The optional headline endpoint has a 35s client cap. Keep it above
    // the server's model budget; scene structure does not use this request.
    const providerSrc = read('services/motionProvider.js');
    // [\d_]+, not \d+: the source writes this as `30_000` (a numeric
    // separator), which \d+ alone truncates to "30" -- silently turning
    // this whole check into a no-op.
    const m = providerSrc.match(/DEFAULT_SCENE_TIMEOUT_MS\s*=\s*([\d_]+)/);
    assert.ok(m, 'DEFAULT_SCENE_TIMEOUT_MS not found in motionProvider.js');
    const serverBudgetMs = Number(m[1].replace(/_/g, ''));
    assert.ok(SF.PLAN_TIMEOUT_MS > serverBudgetMs,
        `client timeout (${SF.PLAN_TIMEOUT_MS}ms) must exceed the server's own budget (${serverBudgetMs}ms), or the client always loses the race`);
});

log(failures ? `\n${failures} FAILURE(S)` : '\nALL SHORT PREVIEW CHECKS PASSED');
process.exit(failures ? 1 : 0);
